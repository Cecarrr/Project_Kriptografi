"""Semua exception aplikasi. UI cukup menangkap CryptVaultError."""


class CryptVaultError(Exception):
    """Basis semua error aplikasi."""


class DongleNotFound(CryptVaultError): ...
class DongleMismatch(CryptVaultError): ...        # dongle tidak terdaftar / serial tidak cocok
class FaceNotMatched(CryptVaultError): ...
class NoFaceDetected(CryptVaultError): ...
class WrongPassword(CryptVaultError): ...
class UserExists(CryptVaultError): ...
class FileTooLarge(CryptVaultError): ...
class UnsupportedFileType(CryptVaultError): ...
class DecryptionError(CryptVaultError): ...       # kunci salah / data rusak
class StegoCapacityError(CryptVaultError): ...
class StegoNotFound(CryptVaultError): ...         # PNG tidak berisi payload
class ChainTampered(CryptVaultError): ...
