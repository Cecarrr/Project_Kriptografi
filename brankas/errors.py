"""Semua exception aplikasi. UI cukup menangkap BrankasError."""


class BrankasError(Exception):
    """Basis semua error aplikasi."""


class DongleNotFound(BrankasError): ...
class DongleMismatch(BrankasError): ...        # dongle tidak terdaftar / serial tidak cocok
class FaceNotMatched(BrankasError): ...
class NoFaceDetected(BrankasError): ...
class WrongPassword(BrankasError): ...
class UserExists(BrankasError): ...
class FileTooLarge(BrankasError): ...
class UnsupportedFileType(BrankasError): ...
class DecryptionError(BrankasError): ...       # kunci salah / data rusak
class StegoCapacityError(BrankasError): ...
class StegoNotFound(BrankasError): ...         # PNG tidak berisi payload
class ChainTampered(BrankasError): ...
class ItemNotFound(BrankasError): ...         # dokumen / catatan / file sumber tidak ditemukan
class InvalidInput(BrankasError): ...         # input pengguna tidak valid (mis. catatan kosong)
class SessionLocked(BrankasError): ...        # sesi sudah dikunci (logout / dongle dicabut)
class UnsafePath(BrankasError): ...           # stored_path tidak berupa nama berkas biasa
